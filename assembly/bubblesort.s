LOOP:
	JUMPREL LOOP

TX_WAIT:
	PUSH R11
	PUSH R12
LOOP_TX:
	LRI R12,0xFFF8 ;Load status register into R12
	ANDI R11,R12,0x2 ;Mask status register to bit 1
	BRNEQ R11,R0,LOOP_TX ;If it is not 0, then loop
	POP R12
	POP R11
	RET

OUTPUT_COUNTER:
	PUSH R1
	PUSH R2
	ADDI R1,R0,31

COPYFOR: ;Copy from ROM to RAM	
	SHLI R5,R4,2 ;Get i * 4
	ADD R6,R5,R2 ;R6 = i*4 + 0x4000
	ADD R7,R5,R1 ;i * 4 + bubblearray pointer
	LRR R8,R7 ;R8 = bubblearray + i * 4
